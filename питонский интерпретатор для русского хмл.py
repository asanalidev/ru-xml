import re

class РуХмлПарсер:
    """Полностью русскоязычный парсер и генератор для файлов .хмл"""
    
    @staticmethod
    def разобрать_файл(путь_к_файлу):
        """Читает файл с расширением .хмл и возвращает структуру данных."""
        with open(путь_к_файлу, 'r', encoding='utf-8') as файл:
            текст = файл.read()
            
        # Проверка заголовка
        заголовок_паттерн = r'<\?хмл\s+кодировка="([^"]+)"\?>'
        заголовок_совпадение = re.search(заголовок_паттерн, текст)
        if not заголовок_совпадение:
            raise ValueError("Ошибка: файл должен начинаться с <?хмл кодировка=\"ЮТФ-8\"?>")
        
        кодировка = заголовок_совпадение.group(1)
        
        # Проверка корневого тега
        корневой_паттерн = r'<ру\.хмл>(.*?)</ру\.хмл>'
        корневой_совпадение = re.search(корневой_паттерн, текст, re.DOTALL)
        if not корневой_совпадение:
            raise ValueError("Ошибка: отсутствует корневой тег <ру.хмл>")
        
        содержимое_корня = корневой_совпадение.group(1)
        
        # Поиск всех кириллических тегов
        элементы_паттерн = r'<([а-яёА-ЯЁ0-9_:]+)>(.*?)</\1>'
        найденные_элементы = re.findall(элементы_паттерн, содержимое_корня, re.DOTALL)
        
        результат = {}
        for тег, значение in найденные_элементы:
            результат[тег] = значение.strip()
            
        return {
            "кодировка": кодировка,
            "данные": результат
        }

    @staticmethod
    def сохранить_в_файл(имя_файла, словарь_данных):
        """Генерирует текст и сохраняет его в файл с расширением .хмл."""
        строки = ['<?хмл кодировка="ЮТФ-8"?>', '<ру.хмл>']
        for ключ, значение in словарь_данных.items():
            строки.append(f'    <{ключ}>{значение}</{ключ}>')
        строки.append('</ру.хмл>')
        
        содержимое = '\n'.join(строки)
        with open(имя_файла, 'w', encoding='utf-8') as файл:
            файл.write(содержимое)
        print(f"Файл '{имя_файла}' успешно сохранен!")


# ==========================================
# Пример использования
# ==========================================

# 1. Данные для записи
мои_данные = {
    "предмет": "какашка",
    "цена:какашки": "100000000000000",
    "описание": "после покупки обязательно смойте в туалет"
}

# 2. Сохраняем в файл с расширением .хмл
РуХмлПарсер.сохранить_в_файл("RU.хмл", мои_данные)

# 3. Читаем созданный файл .хмл обратно в программу
прочитанные_данные = РуХмлПарсер.разобрать_файл("RU.хмл")
print("\nРезультат чтения из файла RU.хмл:")
print(прочитанные_данные)
